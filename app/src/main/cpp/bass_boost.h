#pragma once

#include <cstddef>

namespace auralis {

/**
 * Auralis Bass Boost: a level-aware bass enhancer for stereo Float32 audio.
 *
 * A plain bass-boost slider adds the same low-shelf gain all the time, which eats headroom,
 * muddies loud passages and wastes energy on frequencies small speakers and earphones cannot
 * reproduce. This stage instead combines the techniques used by dedicated speaker DSPs:
 *
 *  1. Dynamic low boost: a true low shelf (so the boost rolls off cleanly with no dip above it) whose
 *     gain eases off as the bass gets louder, so quiet music sounds full and loud music stays tight and clean.
 *  2. Virtual bass: harmonics of the bass band, generated by a level-normalised non-linear
 *     device, so the ear hears deep bass (the "missing fundamental") even on small drivers.
 *  3. Subsonic protection: the boosted band starts at about 30 Hz, so inaudible rumble is not
 *     amplified.
 *  4. Mono bass: the boost is derived from the mid signal and added equally to both channels,
 *     keeping bass centred and stable.
 *  5. JBL-style consumer voicing: the familiar "V" of bass-forward portable speakers and
 *     headphones. A gentle dip around 350 Hz clears the boxy region the extra bass would otherwise
 *     cloud, a presence lift around 3 kHz keeps vocals forward, and a small high-shelf lift at 8 kHz
 *     keeps the added weight from sounding dull. All three scale with the strength.
 *  6. A soft peak guard, so the extra energy never hard-clips.
 *
 * Disabled, the stage is bit-exact pass-through and uses no CPU. Enabling, disabling and changing
 * the amount are smoothed, so there are no clicks. Call all methods from the DSP thread.
 */
class BassBoost {
public:
    void prepare(int sampleRate) noexcept;
    // amount: 0..1 overall strength (about 0.35 low, 0.65 medium, 1.0 high).
    void configure(bool enabled, double amount) noexcept;
    void process(float* interleavedStereo, std::size_t frames) noexcept;

    bool enabled() const noexcept { return enabled_; }
    // Low-shelf lift currently being applied to the bass band, in dB (for tests and diagnostics).
    double currentBoostDb() const noexcept { return boostDb_; }
    // Largest low-shelf lift at full strength.
    static constexpr double kMaxBoostDb = 12.0;

private:
    struct Biquad {
        double b0 = 1.0, b1 = 0.0, b2 = 0.0, a1 = 0.0, a2 = 0.0;
        double z1 = 0.0, z2 = 0.0;
        double process(double x) noexcept {
            const double y = b0 * x + z1;
            z1 = b1 * x - a1 * y + z2;
            z2 = b2 * x - a2 * y;
            return y;
        }
        void reset() noexcept { z1 = 0.0; z2 = 0.0; }
        void lowPass(double sampleRate, double hz, double q) noexcept;
        void highPass(double sampleRate, double hz, double q) noexcept;
        void highShelf(double sampleRate, double hz, double q, double gainDb) noexcept;
        void peaking(double sampleRate, double hz, double q, double gainDb) noexcept;
        void lowShelf(double sampleRate, double hz, double q, double gainDb) noexcept;
        void copyCoefficients(const Biquad& o) noexcept { b0 = o.b0; b1 = o.b1; b2 = o.b2; a1 = o.a1; a2 = o.a2; }
    };

    void resetState() noexcept;
    void updateControl() noexcept;
    void updateVoicing() noexcept;

    double sampleRate_ = 48000.0;
    bool enabled_ = false;
    bool running_ = false;
    double amountTarget_ = 0.0;
    double amount_ = 0.0;
    double mix_ = 0.0;
    double env_ = 0.0;
    double gain_ = 1.0;
    double gainTarget_ = 1.0;
    double boostDb_ = 0.0;
    double voicingAppliedAmount_ = -1.0;
    int controlCounter_ = 0;

    double smoothCoeff_ = 0.0;
    double attackCoeff_ = 0.0;
    double releaseCoeff_ = 0.0;
    double gainCoeff_ = 0.0;

    Biquad subsonic_{};
    Biquad liftSubsonic_{};
    Biquad shelf_{};
    Biquad lowBand_{};
    Biquad harmonicHigh_{};
    Biquad harmonicLow_{};
    Biquad airLeft_{};
    Biquad airRight_{};
    Biquad tuckLeft_{};
    Biquad tuckRight_{};
    Biquad presenceLeft_{};
    Biquad presenceRight_{};
};

} // namespace auralis
